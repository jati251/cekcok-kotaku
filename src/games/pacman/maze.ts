export function cloneMaze(): number[][] {
  return DEFAULT_MAZE.map((row) => [...row]);
}

export function countTotalDots(maze: number[][]): number {
  let count = 0;
  for (let r = 0; r < maze.length; r++) {
    for (let c = 0; c < maze[r].length; c++) {
      if (maze[r][c] === 2 || maze[r][c] === 3) {
        count++;
      }
    }
  }
  return count;
}
